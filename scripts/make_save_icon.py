"""Generate the XMB save data icon (ICON0.PNG, 144x80) as a C header: runtime/src/save_icon.h.

Own artwork (no game assets): dark background, red/blue racing stripes, "GT2" in block letters and "PSP PORT".
Run: python scripts/make_save_icon.py
"""
import struct
import zlib
from pathlib import Path

W, H = 144, 80
FONT = {  # 5x7 block font
    "G": ["01110", "10001", "10000", "10111", "10001", "10001", "01111"],
    "T": ["11111", "00100", "00100", "00100", "00100", "00100", "00100"],
    "2": ["01110", "10001", "00001", "00010", "00100", "01000", "11111"],
    "P": ["11110", "10001", "10001", "11110", "10000", "10000", "10000"],
    "S": ["01111", "10000", "10000", "01110", "00001", "00001", "11110"],
    "O": ["01110", "10001", "10001", "10001", "10001", "10001", "01110"],
    "R": ["11110", "10001", "10001", "11110", "10100", "10010", "10001"],
    " ": ["00000"] * 7,
}


def main() -> None:
    px = [[(18, 20, 28) for _ in range(W)] for _ in range(H)]
    for y in range(H):                                   # diagonal racing stripes
        for x in range(W):
            d = x + y // 2
            if 112 <= d < 124:
                px[y][x] = (200, 30, 40)
            elif 127 <= d < 135:
                px[y][x] = (40, 70, 200)

    def text(s: str, x0: int, y0: int, scale: int, col) -> None:
        for i, ch in enumerate(s):
            for r, row in enumerate(FONT[ch]):
                for c, bit in enumerate(row):
                    if bit == "1":
                        for dy in range(scale):
                            for dx in range(scale):
                                x, y = x0 + (i * 6 + c) * scale + dx, y0 + r * scale + dy
                                if 0 <= x < W and 0 <= y < H:
                                    px[y][x] = col

    text("GT2", 10, 10, 5, (240, 240, 240))
    text("PSP PORT", 10, 56, 2, (255, 170, 40))
    raw = b"".join(b"\0" + bytes(v for p in row for v in p) for row in px)

    def chunk(t: bytes, d: bytes) -> bytes:
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)

    png = (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", W, H, 8, 2, 0, 0, 0)) +
           chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))
    lines = ["/* Generated by scripts/make_save_icon.py - XMB save data icon (ICON0.PNG, 144x80). */",
             "#pragma once", f"static const unsigned char g_save_icon[{len(png)}] __attribute__((aligned(16))) = {{"]
    for i in range(0, len(png), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in png[i:i + 16]) + ",")
    lines.append("};")
    out = Path(__file__).resolve().parent.parent / "runtime" / "src" / "save_icon.h"
    out.write_text("\n".join(lines) + "\n")
    (Path(__file__).resolve().parent.parent / "build").mkdir(exist_ok=True)
    (Path(__file__).resolve().parent.parent / "build" / "save_icon.png").write_bytes(png)
    print(out, len(png), "bytes")


if __name__ == "__main__":
    main()
